gastaldi_criteria <- list(
    include = c(
        "Language: Publications in English.",
        "Topic relevance: Documents describing IPC programmes, IPC manuals/handbooks, structured IPC guidance for healthcare facilities, IPC measures, or content mappable to WHO IPC Core Components.",
        "Type of evidence: All study/document types (systematic reviews, cross-sectional studies, research reports, guidelines, technical documents from WHO/ECDC/national sources, expert opinion, relevant grey literature).",
        "Setting/scope: Evidence applicable to healthcare facilities in any income setting (HICs and LMICs)."
        #"Full-text pertinence: Full texts confirming relevance to building IPC manual/framework content."
    ),
    exclude = c(
        "Language: Publications in languages other than English.",
        "Topic relevance: Documents not coherent with the review objective (no facility-level IPC/manual/programme content).",
        "Type of evidence: Documents without publication references or discussion-only material with no sourceable content.",
        "Setting/scope: Material on infection control not applicable/transferable to healthcare facilities (e.g. purely community, environmental, veterinary, if not clearly adaptable).",
        "Duplicates: Duplicate records identified during the search."
        #"Full-text pertinence: Full texts that, after reading, do not provide usable IPC content for an IPC manual/framework."
    )
)
